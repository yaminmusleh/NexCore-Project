#!/usr/bin/env python3
"""Generates src/WordmarkData.h: the glyph outlines of the NexCore wordmark.

The outlines are taken from the Tektur font (SIL Open Font License 1.1) so that
Studio does not need to ship or load a font file: the welcome page bends these
outlines along an arc itself.

Usage:
    pip install fonttools
    python3 tools/make_wordmark.py  path/to/Tektur[wdth,wght].ttf  [weight]  [width]

The font is available from https://github.com/google/fonts/tree/main/ofl/tektur
(weight 400-900, width 75-100; the default here is weight 700, width 100).
"""
import pathlib
import sys

from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

TEXT = "NexCore"


class PathPen(BasePen):
    """Collects an outline as 'M x y L x y Q cx cy x y Z' (TrueType quadratics)."""

    def __init__(self, glyph_set):
        super().__init__(glyph_set)
        self.parts = []

    @staticmethod
    def _n(value):
        text = f"{round(value, 1):.1f}".rstrip("0").rstrip(".")
        return "0" if text in ("-0", "") else text

    def _moveTo(self, p):
        self.parts.append(f"M {self._n(p[0])} {self._n(p[1])}")

    def _lineTo(self, p):
        self.parts.append(f"L {self._n(p[0])} {self._n(p[1])}")

    def _qCurveToOne(self, c, p):
        self.parts.append(f"Q {self._n(c[0])} {self._n(c[1])} {self._n(p[0])} {self._n(p[1])}")

    def _curveToOne(self, c1, c2, p):
        self.parts.append(f"C {self._n(c1[0])} {self._n(c1[1])} {self._n(c2[0])} {self._n(c2[1])} "
                          f"{self._n(p[0])} {self._n(p[1])}")

    def _closePath(self):
        self.parts.append("Z")


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    font_path = pathlib.Path(sys.argv[1])
    weight = float(sys.argv[2]) if len(sys.argv) > 2 else 700
    width = float(sys.argv[3]) if len(sys.argv) > 3 else 100

    font = instancer.instantiateVariableFont(TTFont(font_path), {"wght": weight, "wdth": width})
    glyph_set = font.getGlyphSet()
    cmap = font.getBestCmap()
    copyright_line = font["name"].getName(0, 3, 1, 0x409).toUnicode()

    entries = []
    for char in TEXT:
        name = cmap[ord(char)]
        pen = PathPen(glyph_set)
        glyph_set[name].draw(pen)
        entries.append((char, " ".join(pen.parts), round(glyph_set[name].width)))

    out = pathlib.Path(__file__).resolve().parent.parent / "src" / "WordmarkData.h"
    lines = [
        "#pragma once",
        "",
        "// Generated by tools/make_wordmark.py -- do not edit by hand.",
        f"// Glyph outlines of \"{TEXT}\" from Tektur, weight {weight:g}, width {width:g}.",
        f"// {copyright_line}",
        "// Licensed under the SIL Open Font License, Version 1.1 (https://openfontlicense.org).",
        "//",
        "// Coordinates are font units (1000 per em), y pointing up, in the commands",
        "// M (move), L (line), Q (quadratic curve), C (cubic curve) and Z (close).",
        "",
        "namespace wordmark {",
        "",
        "struct Glyph {",
        "    const char *path;",
        "    int advance; // horizontal advance in font units",
        "};",
        "",
        "inline constexpr int kUnitsPerEm = 1000;",
        "",
        "inline constexpr Glyph kGlyphs[] = {",
    ]
    for char, path, advance in entries:
        lines.append(f"    // '{char}'")
        lines.append(f'    {{"{path}", {advance}}},')
    lines += ["};", "", "} // namespace wordmark", ""]
    out.write_text("\n".join(lines))
    print(f"wrote {out} ({out.stat().st_size} bytes): "
          + ", ".join(f"{c}={len(p)} chars" for c, p, _ in entries))


if __name__ == "__main__":
    main()